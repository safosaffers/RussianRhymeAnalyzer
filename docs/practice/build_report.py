# ---------------------------------------------------------------- базовый стиль
def setup_styles(doc):
    st = doc.styles["Normal"]
    st.font.name = FONT
    st.font.size = Pt(14)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    st.element.rPr.rFonts.set(qn("w:cs"), FONT)
    pf = st.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(0)
    pf.space_before = Pt(0)

    for name, size, bold, align, caps in [
        ("Heading 1", 16, True, WD_ALIGN_PARAGRAPH.CENTER, True),
        ("Heading 2", 14, True, WD_ALIGN_PARAGRAPH.LEFT, False),
    ]:
        s = doc.styles[name]
        s.font.name = FONT
        s.font.size = Pt(size)
        s.font.bold = bold
        s.font.color.rgb = RGBColor(0, 0, 0)
        s.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
        p = s.paragraph_format
        p.alignment = align
        p.first_line_indent = Cm(0 if align == WD_ALIGN_PARAGRAPH.CENTER else 1.25)
        p.space_before = Pt(12)
        p.space_after = Pt(12)
        p.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
        p.keep_with_next = True

    sec = doc.sections[0]
    sec.page_height, sec.page_width = Mm(297), Mm(210)
    sec.top_margin, sec.bottom_margin = Mm(20), Mm(20)
    sec.left_margin, sec.right_margin = Mm(30), Mm(15)


def _fld(paragraph, instr):
    """Вставка простого поля Word (PAGE, NUMPAGES, TOC)."""
    r = paragraph.add_run()
    b = OxmlElement("w:fldChar"); b.set(qn("w:fldCharType"), "begin")
    it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve"); it.text = instr
    sep = OxmlElement("w:fldChar"); sep.set(qn("w:fldCharType"), "separate")
    t = OxmlElement("w:t"); t.text = ""
    e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), "end")
    for el in (b, it, sep, t, e):
        r._r.append(el)


def page_footer(doc):
    sec = doc.sections[0]
    sec.different_first_page_header_footer = True       # на титуле номер не виден
    f = sec.footer
    p = f.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    _fld(p, "PAGE")
    for run in p.runs:
        run.font.name = FONT; run.font.size = Pt(14)


# ---------------------------------------------------------------- хелперы блоков
def h1(doc, text, page_break=True, toc=True):
    p = doc.add_paragraph(text, style="Heading 1" if toc else "Normal")
    if not toc:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        for r in p.runs:
            r.bold = True
    p.paragraph_format.page_break_before = page_break
    return p


def h2(doc, text):
    return doc.add_paragraph(text, style="Heading 2")


def para(doc, text, justify=True, indent=True, bold=False, align=None):
    p = doc.add_paragraph()
    r = p.add_run(text); r.bold = bold
    if align is not None:
        p.alignment = align
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    return p


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.add_run(it)
        p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE


def table(doc, headers, rows, widths=None, caption=None, num=None):
    if caption and num:
        c = doc.add_paragraph()
        c.paragraph_format.first_line_indent = Cm(0)
        c.add_run(f"Таблица {num} — {caption}")
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for i, htext in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.paragraphs[0].text = ""
        run = cell.paragraphs[0].add_run(htext); run.bold = True
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
    # шрифт в таблице — TNR 12, одинарный интервал
    for r in t.rows:
        for cell in r.cells:
            for p in cell.paragraphs:
                p.paragraph_format.first_line_indent = Cm(0)
                p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
                p.paragraph_format.space_after = Pt(0)
                for run in p.runs:
                    run.font.name = FONT; run.font.size = Pt(12)
    if widths:
        for i, w in enumerate(widths):
            for r in t.rows:
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


def figure(doc, filename, caption, width_cm=16.0):
    """Рисунок по центру + подпись «Рисунок N — …» под ним (ГОСТ 7.32)."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(6)
    p.add_run().add_picture(os.path.join(IMG, filename), width=Cm(width_cm))
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_after = Pt(12)
    c.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    c.add_run(caption)


def listing(doc, code, caption):
    """Подпись «Листинг N — …» + блок кода моноширинным шрифтом (ГОСТ 7.32)."""
    cap = doc.add_paragraph()
    cap.paragraph_format.first_line_indent = Cm(0)
    cap.paragraph_format.space_before = Pt(6)
    cap.paragraph_format.keep_with_next = True
    cap.add_run(caption)
    for raw in code.strip("\n").split("\n"):
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.first_line_indent = Cm(0)
        pf.left_indent = Cm(0.5)
        pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
        pf.space_after = Pt(0)
        pf.space_before = Pt(0)
        pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
        r = p.add_run(raw if raw else " ")
        r.font.name = MONO
        r.font.size = Pt(10)
        r.element.rPr.rFonts.set(qn("w:eastAsia"), MONO)
    doc.add_paragraph().paragraph_format.space_after = Pt(6)


