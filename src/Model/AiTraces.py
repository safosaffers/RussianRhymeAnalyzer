# Model/AiTraces.py
# Детерминированный детектор «машинного следа» в стихе: без обращения к модели,
# только правила из свода (resources/poetics.md, разделы про провалы и запреты).
# Каждый признак возвращается вместе с рецептом правки — его же получает ИИ
# при переписывании, поэтому претензия всегда адресная.
import re

# Затёртые обороты: если читатель может договорить фразу, она ничего не несёт.
CLICHES = (
    "шепот ветра", "шёпот ветра", "танец листвы", "зеркало души", "нити судьбы",
    "крылья мечты", "пламя сердца", "лучи надежды", "слезы дождя", "слёзы дождя",
    "тень прошлого", "холод одиночества", "океан любви", "искры страсти",
    "дыхание весны", "объятия ночи", "серебро луны", "золото заката",
    "вечный покой", "рука судьбы", "свет во тьме", "музыка души",
    "как в сказке", "словно птица", "как лед", "как лёд", "как сон",
)

# Прямо названное чувство — вместо повода и предмета, из которых оно следует.
FEELINGS = (
    "тоска", "тоски", "тоской", "печаль", "печали", "грусть", "грусти",
    "радость", "радости", "счастье", "счастья", "боль", "боли", "страх",
    "страха", "любовь", "любви", "ненависть", "отчаяние", "отчаянье",
    "одиночество", "одиночества", "нежность", "нежности", "обида", "обиды",
)

# Отвлечённые слова: разрешены только после того, как оплачены деталью.
ABSTRACT_STEMS = (
    "вечност", "бесконечност", "судьб", "мечт", "бытие", "вселенн", "истин",
    "свобод", "надежд", "забвень", "забвени", "пустот", "мирозда", "смысл",
)
ABSTRACT_EXACT = (
    "душа", "души", "душу", "душой", "душе", "дух", "духа",
    "свет", "света", "свету", "светом", "тьма", "тьмы", "тьме", "тьму", "тьмой",
    "время", "времени", "вечность", "рок", "рока",
)

# Маркеры вывода: финал, который объясняет читателю прочитанное.
CONCLUSION_MARKERS = (
    "и значит", "а значит", "и потому", "поэтому", "вот и", "итак",
    "в этом и", "и в этом", "тем самым", "но всё же", "но все же", "оттого",
    "так и знай", "такова", "таков",
)

# Связки: строка, где ничего не происходит.
COPULAS = ("был", "была", "было", "были", "есть", "это", "являюсь", "является")

_WORD_RE = re.compile(r"[а-яёА-ЯЁ]+")


def _words(line: str) -> list[str]:
    return [w.lower() for w in _WORD_RE.findall(line)]


def _lines(text: str) -> list[str]:
    return [ln.strip() for ln in text.splitlines() if ln.strip()]


def _is_abstract(word: str) -> bool:
    return word in ABSTRACT_EXACT or any(word.startswith(s) for s in ABSTRACT_STEMS)


def ai_traces(text: str) -> list[dict]:
    """Признаки машинного текста: [{code, line, msg, fix}].

    line = 0 — претензия к стиху целиком, иначе номер строки (с единицы).
    Пустой список означает лишь то, что автоматические правила молчат;
    смысловую оценку это не заменяет.
    """
    lines = _lines(text)
    if not lines:
        return []
    out = []

    # 1. Строка = законченная фраза во всём стихе: ни одного переноса.
    # Ровность длин строк здесь НЕ проверяется: в силлабо-тонике она задана
    # размером, это требование формы, а не след машины.
    if len(lines) >= 4:
        closed = sum(1 for ln in lines[:-1] if ln.rstrip()[-1] in ".,;:!?-—…")
        if closed == len(lines) - 1:
            out.append({
                "code": "no_enjambment", "line": 0,
                "msg": "каждая строка — законченная фраза, ни одного переноса",
                "fix": "хотя бы раз перенести фразу через границу строки: "
                       "перенос даёт двойное чтение",
            })
        heads = sum(1 for ln in lines if _words(ln) and _words(ln)[0] in ("и", "а", "но"))
        if heads >= len(lines) / 2:
            out.append({
                "code": "anaphora_conj", "line": 0,
                "msg": f"половина строк начинается с союза ({heads} из {len(lines)})",
                "fix": "убрать сцепку союзами: пусть строки стыкуются образом, "
                       "а не «и»",
            })

    for i, ln in enumerate(lines, 1):
        low = ln.lower()
        ws = _words(ln)

        for c in CLICHES:
            if c in low:
                out.append({
                    "code": "cliche", "line": i, "msg": f"затёртый оборот «{c}»",
                    "fix": "сломать привычное сочетание: назвать предмет заново",
                })
                break

        named = [w for w in ws if w in FEELINGS]
        if named:
            out.append({
                "code": "named_feeling", "line": i,
                "msg": f"чувство названо прямо: «{named[0]}»",
                "fix": "убрать слово чувства, оставить повод и предмет, из которых "
                       "оно следует",
            })

        if sum(1 for w in ws if w in COPULAS) and len(ws) <= 8 and \
                not any(w.endswith(("ет", "ит", "ут", "ют", "ат", "ят", "ал", "ил",
                                    "ыл", "ел", "ул", "ла", "ло", "ли")) for w in ws):
            out.append({
                "code": "copula", "line": i, "msg": "строка держится на связке",
                "fix": "переписать переходным глаголом: пусть предмет действует",
            })

    # 2. Плотность отвлечённых слов по стиху целиком.
    abstract = [(i, w) for i, ln in enumerate(lines, 1)
                for w in _words(ln) if _is_abstract(w)]
    if len(abstract) >= max(2, len(lines) // 2):
        uniq = ", ".join(dict.fromkeys(w for _, w in abstract))
        out.append({
            "code": "abstract_flood", "line": 0,
            "msg": f"отвлечённых слов больше, чем деталей: {uniq}",
            "fix": "каждое отвлечённое слово оплатить предметом или убрать",
        })

    # 3. Финал-вывод.
    last = lines[-1].lower()
    for m in CONCLUSION_MARKERS:
        if m in last:
            out.append({
                "code": "conclusion_end", "line": len(lines),
                "msg": f"финал объясняет прочитанное («{m}»)",
                "fix": "удалить последнюю строку или заменить образом без вывода",
            })
            break

    return out


def traces_text(traces: list[dict]) -> str:
    """Признаки одной строкой — для подсказки модели при переписывании."""
    if not traces:
        return ""
    parts = []
    for t in traces:
        where = f"строка {t['line']}" if t["line"] else "весь стих"
        parts.append(f"{where}: {t['msg']} -> {t['fix']}")
    return "; ".join(parts) + "."
